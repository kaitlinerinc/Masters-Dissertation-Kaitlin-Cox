# Identify Potential Duplicates for Manual Review
#-------------------------------------------------------
find_duplicate_candidates <- function(df, threshold = 0.70) {
  cat("Scanning for potential duplicates (Similarity >= ", threshold, ")... \n")
  
  df$Total_Tokens <- as.numeric(df$Total_Tokens)
  n_rows <- nrow(df)
  
  # Pre-compute word sets
  word_sets <- lapply(df$CleanedText, function(text) {
    unique(unlist(str_split(text, "\\s+")))
  })
  
  # Initialize result list
  candidate_list <- list()
  counter <- 1
  
  for (i in seq_len(n_rows - 1)) {
    set_i <- word_sets[[i]]
    id_i <- df$Ad_Base_ID[i]
    
    for (j in (i + 1):n_rows) {
      set_j <- word_sets[[j]]
      id_j <- df$Ad_Base_ID[j]
      
      # Calculate Jaccard
      intersect_len <- length(intersect(set_i, set_j))
      union_len <- length(set_i) + length(set_j) - intersect_len
      jaccard_sim <- ifelse(union_len == 0, 0, intersect_len / union_len)
      
      # Flag if meets threshold
      if (jaccard_sim >= threshold) {
        candidate_list[[counter]] <- data.frame(
          Ad_1 = id_i,
          Ad_2 = id_j,
          Similarity = round(jaccard_sim, 3)
        )
        counter <- counter + 1
      }
    }
  }
  
  if (length(candidate_list) > 0) {
    results <- do.call(rbind, candidate_list)
    return(results)
  } else {
    cat("No pairs found above", threshold, "\n")
    return(NULL)
  }
}

