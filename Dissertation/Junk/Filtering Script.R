#-------------------------------------------------------
# Remove Jaccard Duplicates with Length Tolerance
#-------------------------------------------------------
remove_jaccard_duplicates <- function(df, threshold, length_tol) {
  
  cat("Starting Jaccard deduplication...\n")
  cat("Total starting rows:", nrow(df), "\n")
  
  # Ensure Total_Tokens is numeric
  df$Total_Tokens <- as.numeric(df$Total_Tokens)
  
  duplicates_to_remove <- integer(0)
  n_rows <- nrow(df)
  
  # Pre-compute word sets to optimize the nested loop
  # Uses CleanedText as generated by the OCR pipeline
  word_sets <- lapply(df$CleanedText, function(text) {
    unique(unlist(str_split(text, "\\s+")))
  })
  
  for (i in seq_len(n_rows - 1)) {
    
    # Skip if already marked for removal
    if (i %in% duplicates_to_remove) next
    
    len_i <- df$Total_Tokens[i]
    set_i <- word_sets[[i]]
    
    for (j in (i + 1):n_rows) {
      
      # Skip if already marked for removal
      if (j %in% duplicates_to_remove) next
      
      len_j <- df$Total_Tokens[j]
      
      # Step 1: Check Length Tolerance (+/- 20%)
      lower_bound <- len_i * (1 - length_tol)
      upper_bound <- len_i * (1 + length_tol)
      
      if (len_j >= lower_bound && len_j <= upper_bound) {
        
        # Step 2: Calculate Jaccard Similarity
        set_j <- word_sets[[j]]
        
        intersect_len <- length(intersect(set_i, set_j))
        union_len <- length(set_i) + length(set_j) - intersect_len
        
        jaccard_sim <- ifelse(union_len == 0, 0, intersect_len / union_len)
        
        # Step 3: Flag for removal if threshold is met
        if (jaccard_sim >= threshold) {
          duplicates_to_remove <- c(duplicates_to_remove, j)
        }
      }
    }
  }
  
  # Remove flagged indices and report
  if (length(duplicates_to_remove) > 0) {
    cat(sprintf("Removed %d duplicate(s) (Similarity >= %s, Length Tol = +/- %s%%)\n", 
                length(duplicates_to_remove), threshold, length_tol * 100))
    return(df[-duplicates_to_remove, ])
  } else {
    cat("No duplicates found meeting the criteria.\n")
    return(df)
  }
}

